<script setup lang="ts">
import { useUpdateDraftAppConfig } from '@/hooks/use-app'
import { nextTick, ref, watch } from 'vue'
import { cloneDeep, isEqual } from 'lodash'
const props = defineProps({
  app_id: { type: String, default: '', required: true },
  review_config: { type: Object, default: {}, required: true },
})
const { loading, handleUpdateDraftAppConfig } = useUpdateDraftAppConfig()
const isInit = ref(false)
const reviewConfigModalVisible = ref(false)
const reviewConfigForm = ref({
  enable: props.review_config?.enable,
  keywords: props.review_config?.keywords?.join('\n'),
  inputs_config: {
    enable: props.review_config?.inputs_config?.enable,
    preset_response: props.review_config?.inputs_config?.preset_response,
  },
  outputs_config: {
    enable: props.review_config?.outputs_config?.enable,
  },
})
const originReviewConfigForm = ref({ ...cloneDeep(reviewConfigForm.value) })

// Define the form modification checking function
const isFormModified = () => {
  return isEqual(originReviewConfigForm.value, reviewConfigForm.value)
}
//Hidden review Configuration Modal
const handleCancelReviewConfigModal = () => {

  reviewConfigModalVisible.value = false
  reviewConfigForm.value = cloneDeep(originReviewConfigForm.value)
}

//Submit the data that store in the review modal window
const handleSubmitReviewConfig = async () => {
  try {
    //Call the update app draft config api to submit the data
    await handleUpdateDraftAppConfig(props.app_id, {
      review_config: {
        enable: reviewConfigForm.value.enable,
        keywords: reviewConfigForm.value.keywords
          .split(/\r?\n/)
          .filter((item: string) => item.trim() !== ''),
        inputs_config: reviewConfigForm.value.inputs_config,
        outputs_config: reviewConfigForm.value.outputs_config,
      },
    })

    // Interface updated successfully, synchronizing form information
    originReviewConfigForm.value = cloneDeep(reviewConfigForm.value)
    await nextTick()

    // Hide a modal window
    handleCancelReviewConfigModal()
  } catch (e) {}
}
// Listen to changes in review_config and synchronize them to the form
watch(
  () => props.review_config,
  (newValue: any) => {
    // Check whether the detection data is updated and not initialized
    if (!isInit.value || !isFormModified()) {
      if (newValue && Object.keys(newValue).length > 0) {
        // Update form data and backup data with deep copy
        reviewConfigForm.value = cloneDeep({ ...newValue, keywords: newValue?.keywords.join('\n') })
        originReviewConfigForm.value = cloneDeep({
          ...newValue,
          keywords: newValue?.keywords.join('\n'),
        })
        // Marked as initialized
        isInit.value = true
      }
    }
  },
  { immediate: true, deep: true },
)

</script>

<template>
  <div class="">
    <a-collapse-item key="review_config" class="app-ability-item review-config-ability-item">
      <template #header>
        <div class="text-gray-700 font-bold">Content Review</div>
      </template>
      <template #extra>
        <a-dropdown
          @select="
            async (value) => {
              if (Boolean(value) !== reviewConfigForm.enable) {
                try {
                  // Override the data of form and ensure the data synchronization
                  reviewConfigForm.enable = Boolean(value)
                  await nextTick()

                  // Submit the form and update the data
                  await handleSubmitReviewConfig()
                } catch (e) {}
              }
            }
          "
        >
          <a-button size="mini" class="rounded-lg flex items-center gap-1 px-1" @click.stop>
            {{ reviewConfigForm.enable ? 'Enable' : 'Disable' }}
            <icon-down />
          </a-button>
          <template #content>
            <a-doption :value="1" class="text-xs py-1.5 text-gray-700">Enable</a-doption>
            <a-doption :value="0" class="text-xs py-1.5 text-red-700">Disable</a-doption>
          </template>
        </a-dropdown>
      </template>
      <div class="group py-2">
        <div
          class="text-xs text-gray-500 leading-[22px]"
          :class="{ 'group-hover:hidden': reviewConfigForm.enable }"
        >
          Review user input and the output generated by large language models
        </div>
        <a-button
          v-if="reviewConfigForm.enable"
          size="small"
          long
          class="hidden group-hover:block rounded-lg transition-all"
          @click="reviewConfigModalVisible = true"
        >
          <template #icon>
            <icon-settings />
          </template>
          Settings
        </a-button>
      </div>
    </a-collapse-item>
    <!-- 模态窗组件 -->
    <a-modal
      :visible="reviewConfigModalVisible"
      hide-title
      :footer="false"
      modal-class="rounded-xl"
      @cancel="handleCancelReviewConfigModal"
    >
      <!-- 顶部标题 -->
      <div class="flex items-center justify-between">
        <div class="text-lg font-bold text-gray-700">Content Review</div>
        <a-button
          type="text"
          class="!text-gray-700"
          size="small"
          @click="handleCancelReviewConfigModal"
        >
          <template #icon>
            <icon-close />
          </template>
        </a-button>
      </div>
      <!-- 中间表单 -->
      <div class="py-4">
        <div class="flex flex-col gap-5">
          <!-- 关键词 -->
          <div class="flex flex-col gap-2">
            <div class="flex flex-col">
              <div class="flex items-center gap-1 text-gray-700">
                Keywords
                <div class="text-red-700">*</div>
              </div>
              <div class="text-gray-500 text-xs">One keyword per line, separated by line breaks, up to 100 keywords.</div>
            </div>
            <a-textarea
              v-model:model-value="reviewConfigForm.keywords"
              class="bg-white rounded-lg border border-gray-200"
              placeholder="One item per line, separated by line breaks."
              :max-length="100"
              show-word-limit
              :auto-size="{ minRows: 4, maxRows: 4 }"
              :word-length="
                (value) => {
                  if (value.trim() === '') return 0
                  return value.split(/\r?\n/).length
                }
              "
              :word-slice="
                (value, maxLength) => {
                  // Split the content and extract the first 100 keywords
                  const lines = value.split(/\r?\n/)
                  const first100Lines = lines.slice(0, maxLength)

                  // Return after concatenating line breaks
                  return first100Lines.join('\n')
                }
              "
            />
          </div>
          <!-- 输入审核 -->
          <div class="flex flex-col gap-2 p-3 bg-gray-50 border border-gray-200 rounded-lg">
            <div class="flex items-center justify-between">
              <div class="text-gray-700">Input review content</div>
              <a-switch
                v-model:model-value="reviewConfigForm.inputs_config.enable"
                size="small"
                type="round"
              />
            </div>
            <div class="flex flex-col gap-2">
              <div class="text-gray-700 text-xs">Preset reply</div>
              <a-textarea
                v-model:model-value="reviewConfigForm.inputs_config.preset_response"
                placeholder="This is the preset reply content"
                class="bg-white rounded-lg border border-gray-200"
                :auto-size="{ minRows: 3, maxRows: 3 }"
              />
            </div>
          </div>
          <!-- 输出审核 -->
          <div class="flex flex-col p-3 bg-gray-50 border border-gray-200 rounded-lg">
            <div class="flex items-center justify-between">
              <div class="text-gray-700">Output review content</div>
              <a-switch
                v-model:model-value="reviewConfigForm.outputs_config.enable"
                size="small"
                type="round"
              />
            </div>
          </div>
        </div>
      </div>
      <!-- 底部按钮 -->
      <div class="flex items-center justify-between">
        <div class=""></div>
        <a-space :size="16">
          <a-button class="rounded-lg" @click="handleCancelReviewConfigModal">Cancel</a-button>
          <a-button
            :loading="loading"
            type="primary"
            class="rounded-lg"
            @click="handleSubmitReviewConfig"
          >
            Save
          </a-button>
        </a-space>
      </div>
    </a-modal>
  </div>
</template>

